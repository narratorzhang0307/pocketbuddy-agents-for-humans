// Convert imagegen edits into firmware JPEGs and a timed preview. Never redraw
// the dog or change the existing Frost/OSS catalog. Run from any directory.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const out = join(root, 'public/assets/frost-talk/20260828');
const board = join(root, 'hardware/ojbadge-agent-link/boards/ojbadge');
const source = join(root, 'public/assets/skill-avatars/20260827/originals/frost.png');
const hash = b => createHash('sha256').update(b).digest('hex');
const originalHash = hash(await readFile(source));
const names = ['rest', 'small', 'open', 'blink', 'wink'];
const frames = [], manifest = [], arrays = [];
await mkdir(join(out, 'hardware'), { recursive: true });
for (const [i, name] of names.entries()) {
  const original = name === 'rest' ? source : join(out, 'originals', `${name}.png`);
  const input = await readFile(original);
  const meta = await sharp(input).metadata();
  if (meta.width !== 1254 || meta.height !== 1254) throw new Error(`Unexpected frame size: ${name}`);
  const jpeg = name === 'rest'
    ? await readFile(join(root, 'public/assets/skill-avatars/20260827/hardware-round/frost.jpg'))
    : await sharp(input).resize(240, 240).flatten().removeAlpha()
      .jpeg({ quality: 94, chromaSubsampling: '4:4:4', progressive: false }).toBuffer();
  const info = await sharp(jpeg).metadata();
  if (info.width !== 240 || info.height !== 240 || info.isProgressive || jpeg.length > 65536)
    throw new Error(`Invalid hardware JPEG: ${name}`);
  await writeFile(join(out, 'hardware', `${name}.jpg`), jpeg);
  frames.push(jpeg);
  manifest.push({ name, index: i, bytes: jpeg.length, sha256: hash(jpeg), sourceSha256: hash(input) });
  if (i) {
    const bytes = Array.from(jpeg, byte => `0x${byte.toString(16).padStart(2, '0')}`);
    arrays.push(`static const uint8_t kFrame${i}[] = { // ${name}\n${Array.from({ length: Math.ceil(bytes.length / 24) }, (_, row) => `  ${bytes.slice(row * 24, row * 24 + 24).join(',')},`).join('\n')}\n};`);
  }
}
await writeFile(join(board, 'frost_talk_assets.cc'), `// GENERATED by scripts/hardware/build-frost-talk-assets.mjs.\n// Additional expressions for resident Frost only. Existing rest JPEG is reused.\n#include "frost_talk_assets.h"\nnamespace frost_talk {\n${arrays.join('\n')}\nconst frost_avatar::Asset kFrames[4] = {\n  {kFrame1, sizeof(kFrame1)}, {kFrame2, sizeof(kFrame2)}, {kFrame3, sizeof(kFrame3)}, {kFrame4, sizeof(kFrame4)}\n};\n}\n`);

// Presentation-only circular viewport; these pixels are never firmware assets.
// The artwork itself comes exclusively from the original and imagegen edits.
const size = 360;
const circle = Buffer.from(`<svg width="${size}" height="${size}"><circle cx="180" cy="180" r="180" fill="white"/></svg>`);
const previews = await Promise.all(frames.map(frame => sharp(frame).resize(size, size)
  .ensureAlpha().composite([{ input: circle, blend: 'dest-in' }]).raw().toBuffer()));
// Illustrative cadence: mouth motion -> double-eye squint -> mouth -> wink.
// Firmware has its own continuous idle clock; real PCM can soften the mouth.
const phrase = [[0,120],[1,120],[2,120],[1,120],[0,120],[1,120],[2,120],[1,120],[0,200],
  [1,120],[2,120],[1,120],[0,120],[3,1600],[1,120],[2,120],[1,120],[0,120],
  [1,120],[2,120],[1,120],[0,120],[1,120],[2,120],[0,120]];
const sequence = [...phrase, ...phrase.map(([index, ms]) => [index === 3 ? 4 : index, ms])];
const raw = Buffer.concat(sequence.map(([index]) => previews[index]));
const input = { raw: { width: size, height: size * sequence.length, channels: 4, pageHeight: size } };
const delay = sequence.map(([, ms]) => ms);
await sharp(raw, input).webp({ lossless: true, loop: 0, delay }).toFile(join(out, 'frost-speaking.webp'));
await sharp(raw, input).gif({ loop: 0, delay, colours: 128, dither: 0 }).toFile(join(out, 'frost-speaking.gif'));
const addedBytes = manifest.slice(1).reduce((sum, f) => sum + f.bytes, 0);
await writeFile(join(out, 'manifest.json'), JSON.stringify({
  schema: 'frost-talk/v1', generator: 'built-in image_gen edits + sharp format conversion',
  hardwareSize: 240, originalSha256: originalHash, addedFlashImageBytes: addedBytes,
  extraFramebuffers: 0, preview: 'illustrative cadence, no recorded speech', sequence, frames: manifest,
}, null, 2) + '\n');
if (hash(await readFile(source)) !== originalHash) throw new Error('Original Frost changed');
console.log(JSON.stringify({ frames: manifest.map(({ name, bytes }) => ({ name, bytes })), addedFlashImageBytes: addedBytes, originalUnchanged: true }));
