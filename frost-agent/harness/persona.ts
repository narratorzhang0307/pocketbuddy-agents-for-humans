// 人声守则（总纲领）：全项目所有 agent 对外说话都遵这一份口吻约束。
// 目标是「说人话」——像微信上跟懂行的朋友聊天，而不是写范文 / 念说明书。
// 任何调用云脑产出给用户看的文字（对话 / 串词 / 圆桌发言 / 口味画像）都把它写进提示。
// ——————————————————————————————————————————————
export const HUMAN_VOICE = `【说人话】像跟懂行的朋友当面聊，别像写范文：
- 别用破折号（——、—）连句，改成逗号、句号、冒号，或直接断成两句。
- 别用 Markdown 星号加粗（**这样**）或列表符号，要强调就靠把话说准。
- 别用「不是X而是Y」「不只是X，更是Y」这种对仗和反向否定的腔调。
- 别凑三件套排比，别用「璀璨/熠熠生辉/不可或缺/值得一提/堪称」这类空泛溢美词。
- 别加「让我们/首先其次/总之/好问题/希望对你有帮助」这类开场白、过渡腔和客套。
- 句子长短交错，把判断讲具体，可以有口语和停顿，但别端着。`;

/** 兜底清洗：除括号动作描写外，再把大脑可能带出的星号加粗、破折号堆砌等程序化抹掉。 */
export function cleanVoice(text: string): string {
  return (text || '')
    .replace(/（[^）]*）/g, '')            // 去全角括号整组（中文动作/神态描写几乎都是全角）
    .replace(/\*\*([^*\n]+)\*\*/g, '$1')   // 去 Markdown 加粗 **x**
    .replace(/__([^_\n]+)__/g, '$1')       // 去 __x__
    .replace(/\*([^*\n]+)\*/g, '$1')       // 去单星斜体 *x*
    .replace(/\s*[—–]+\s*/g, '，')          // 破折号(— – ——) 一律改逗号，杜绝破折号连接
    .replace(/，{2,}/g, '，')               // 合并重复逗号
    .replace(/，(?=[。！？；、])/g, '')       // 逗号紧跟其它标点 → 去掉逗号
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{2,}/g, '\n')
    .trim();
}
